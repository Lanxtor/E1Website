#!/usr/bin/env python3
"""Builds the E1 user guides (the Academy's "User guides" on the account page).

Sources (edit these, never the generated pages):
  tools/guides/categories.json      the categories, their order, page, icon and summary
  tools/guides/src/<id>.html        one fragment per category: <section class="g-feature"> blocks
  tools/guides/features/<id>.json   the features of that category (the catalog)
  tools/guides/roadmap.json         the app and website roadmaps (exported from Lanxtor/E1,
                                    see docs/USER-GUIDES.md)

Writes:
  guide.html                        the hub: categories, what's new, under development
  guide-<id>.html                   one page per category
  guide-features.html               every feature in one table, with status and dates
  guide-roadmap.html                what is being built, milestone by milestone
  assets/data/user-guide-features.json   the whole catalog, for training videos and test plans

Run: python3 tools/guides/build.py            (build)
     python3 tools/guides/build.py --check    (also fail on broken links, ids or images)
"""
import html
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "tools", "guides")
STATUS = {
    "available": "Available",
    "under-development": "Under development",
    "planned": "Planned",
    "placeholder": "Placeholder",
    "preview": "Preview data only",
    "parked": "Parked",
}
CSS_V = "2"


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, text):
    full = os.path.join(ROOT, path)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def esc(s):
    return html.escape(s or "", quote=True)


PALETTE = re.compile(r"palette|Ctrl\+K|⌘K", re.I)


def no_palette(text):
    """The command palette is being removed (owner, 2026-11-07): the guides never mention it,
    not even where they quote the roadmap."""
    if not text or not PALETTE.search(text):
        return text
    text = re.sub(r",? (?:and |with )?(?:the )?command palette", "", text, flags=re.I)
    parts = re.split(r"(?<=[.!?])\s+", text)
    return " ".join(p for p in parts if not PALETTE.search(p)).strip()


def load():
    cats = json.loads(read(os.path.join(SRC, "categories.json")))
    features = []
    for cat in cats["categories"]:
        path = os.path.join(SRC, "features", cat["id"] + ".json")
        items = json.loads(read(path)) if os.path.exists(path) else []
        for item in items:
            item["category"] = cat["id"]
            item.setdefault("page", "guide-%s.html#%s" % (cat["id"], item.get("anchor", "")))
            features.append(item)
    roadmap_path = os.path.join(SRC, "roadmap.json")
    roadmap = json.loads(read(roadmap_path)) if os.path.exists(roadmap_path) else None
    if roadmap:
        for key in ("app", "website"):
            for m in roadmap[key]["milestones"]:
                m["summary"] = no_palette(m["summary"])
                for st in m["stages"]:
                    st["title"] = no_palette(st["title"])
                    st["tryIt"] = no_palette(st["tryIt"])
    return cats, features, roadmap


def page(title, description, body, toc, crumbs):
    return """<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title} — E1 user guide</title>
  <meta name="description" content="{desc}">
  <meta name="robots" content="noindex">
  <link rel="icon" href="assets/img/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="assets/css/styles.css?v=74">
  <link rel="stylesheet" href="assets/css/guides.css?v={css}">
</head>
<body>
  <!-- Generated by tools/guides/build.py from tools/guides/. Do not edit this file. -->
  <div id="site-header"></div>

  <main class="guide-page">
    <div class="container guide-layout">
      <nav class="guide-toc" aria-label="User guide">
{toc}
      </nav>
      <article class="guide-main">
        <p class="guide-crumbs">{crumbs}</p>
{body}
      </article>
    </div>
  </main>

  <div id="site-footer"></div>
  <script src="assets/js/i18n-dict.js?v=2"></script>
  <script src="assets/js/i18n.js?v=1"></script>
  <script src="assets/js/config.js?v=3"></script>
  <script src="assets/js/e1-api.js?v=6"></script>
  <script src="assets/js/main.js?v=30"></script>
  <script src="assets/js/chat.js?v=6"></script>
  <script src="assets/js/guides.js?v=1"></script>
</body>
</html>
""".format(title=esc(title), desc=esc(description), css=CSS_V, toc=toc, crumbs=crumbs, body=body)


def nav_toc(cats, current, sections=None):
    out = ['        <h2>User guide</h2>', '        <ol>']
    links = [("guide.html", "Overview")] + [("guide-%s.html" % c["id"], "%d. %s" % (i + 1, c["title"])) for i, c in enumerate(cats)]
    links += [("guide-features.html", "All features"), ("guide-roadmap.html", "Under development and roadmap")]
    for href, label in links:
        cur = ' aria-current="page"' if href == current else ""
        out.append('          <li><a href="%s"%s>%s</a></li>' % (href, cur, esc(label)))
    out.append("        </ol>")
    if sections:
        out.append("        <h2>On this page</h2>")
        out.append("        <ol>")
        for sid, label in sections:
            out.append('          <li><a href="#%s">%s</a></li>' % (sid, esc(label)))
        out.append("        </ol>")
    return "\n".join(out)


FIG_RE = re.compile(r'<figure class="(g-shot[^"]*)"(?: style="[^"]*")?>(\s*<img [^>]*?width="(\d+)" height="(\d+)")')


def size_figures(frag):
    """Shows each screenshot at its size on screen (they are taken at device scale 2),
    never wider than the column and never taller than 720 px, so a narrow crop such as
    a menu is not blown up across the page."""
    def fix(m):
        w, h = int(m.group(3)), int(m.group(4))
        css = w / 2 if w < 2160 else 1080  # full screens: 1440 px wide, stored at 2160
        css = min(css, 720 * w / h)
        return '<figure class="%s" style="max-width:%dpx">%s' % (m.group(1), round(css), m.group(2))
    return FIG_RE.sub(fix, frag)


SECTION_RE = re.compile(r'<section class="g-feature[^"]*" id="([^"]+)"[^>]*>\s*<h2>(.*?)</h2>', re.S)


def strip_tags(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def crumbs(*parts):
    items = ['<a href="account.html#academy-guides">Academy</a>', '<a href="guide.html">User guide</a>'] + list(parts)
    return " / ".join(items)


def status_badge(status):
    return '<span class="g-status %s">%s</span>' % (status, STATUS.get(status, status))


def feature_link(f):
    return '<a href="%s">%s</a>' % (esc(f["page"]), esc(f["title"]))


def build():
    meta, features, roadmap = load()
    cats = meta["categories"]
    by_cat = {c["id"]: [f for f in features if f["category"] == c["id"]] for c in cats}

    # Category pages
    for i, c in enumerate(cats):
        frag_path = os.path.join(SRC, "src", c["id"] + ".html")
        frag = size_figures(read(frag_path)) if os.path.exists(frag_path) else "<p>This guide is being written.</p>"
        sections = [(sid, strip_tags(h)) for sid, h in SECTION_RE.findall(frag)]
        n_av = sum(1 for f in by_cat[c["id"]] if f["status"] == "available")
        head = (
            '        <h1>%d. %s</h1>\n        <p class="lead">%s</p>\n'
            '        <div class="g-meta"><span>%d features</span><span>%d available</span><span>Guide updated %s</span></div>\n'
            % (i + 1, esc(c["title"]), esc(c["summary"]), len(by_cat[c["id"]]), n_av, esc(c.get("updated", meta["updated"])))
        )
        nxt = cats[i + 1] if i + 1 < len(cats) else None
        prv = cats[i - 1] if i > 0 else None
        pager = '\n        <p class="g-related">'
        if prv:
            pager += '← <a href="guide-%s.html">%s</a>' % (prv["id"], esc(prv["title"]))
        if prv and nxt:
            pager += " · "
        if nxt:
            pager += '<a href="guide-%s.html">%s</a> →' % (nxt["id"], esc(nxt["title"]))
        pager += "</p>\n"
        write("guide-%s.html" % c["id"], page(c["title"], c["summary"], head + frag + pager, nav_toc(cats, "guide-%s.html" % c["id"], sections), crumbs(esc(c["title"]))))

    # Hub
    cards = []
    for i, c in enumerate(cats):
        fs = by_cat[c["id"]]
        cards.append(
            '          <a class="card" href="guide-%s.html">\n            %s\n            <h3>%d. %s</h3>\n            <p>%s</p>\n            <p class="g-count">%d features · %d available</p>\n          </a>'
            % (c["id"], c.get("icon", ""), i + 1, esc(c["title"]), esc(c["summary"]), len(fs), sum(1 for f in fs if f["status"] == "available"))
        )
    dated = sorted([f for f in features if f.get("updated") or f.get("since")], key=lambda f: (f.get("updated") or f.get("since")), reverse=True)
    news = "\n".join(
        '            <li><time datetime="{d}">{d}</time><span>{link} {badge} <span class="muted">— {cat}</span></span></li>'.format(
            d=esc(f.get("updated") or f.get("since")), link=feature_link(f), badge=status_badge(f["status"]),
            cat=esc(next(c["title"] for c in cats if c["id"] == f["category"])))
        for f in dated[:30])
    dev = [f for f in features if f["status"] in ("under-development", "planned")]
    devlist = "\n".join('            <li><span class="muted">%s</span><span>%s %s</span></li>' % (esc(f.get("roadmap", [""])[0] if f.get("roadmap") else ""), feature_link(f), status_badge(f["status"])) for f in dev)
    counts = {s: sum(1 for f in features if f["status"] == s) for s in STATUS}
    hub = """        <h1>E1 user guide</h1>
        <p class="lead">{intro}</p>
        <div class="g-meta"><span>{total} features</span>{counts}<span>Guide updated {upd}</span></div>
        <div class="g-intro">
          <p>Every guide describes one feature the way you meet it on screen: where to find it, who may use it, what to do step by step, and what you should see after each step. The labels in <span class="ui">bold</span> are the exact words on the screen. Each feature carries its status and the date it was delivered or last changed, so you always know whether you are reading about something you can use today.</p>
          <p>The screenshots were taken from E1 on {shots}, in the default dark appearance, with a small demo project (a pump train on one sheet).</p>
        </div>
        <div class="grid grid-3 g-cats">
{cards}
        </div>
        <section class="g-block" id="whats-new">
          <h2>What's new</h2>
          <p>The latest features and changes, newest first. <a href="guide-features.html">All features</a> lists every one.</p>
          <ul class="g-news">
{news}
          </ul>
        </section>
        <section class="g-block" id="under-development">
          <h2>Under development</h2>
          <p>Being built now or planned next. These are described in the guides so you can prepare, but they are not in E1 yet. <a href="guide-roadmap.html">The roadmap</a> shows every stage.</p>
          <ul class="g-news">
{dev}
          </ul>
        </section>
        <section class="g-block" id="statuses">
          <h2>What the statuses mean</h2>
          <dl class="g-facts">
            <dt>{s_av}</dt><dd>In E1 today. You can follow the steps and should see what is described.</dd>
            <dt>{s_ud}</dt><dd>Being built now. The guide describes the planned behavior; labels may still change.</dd>
            <dt>{s_pl}</dt><dd>Decided and scheduled on the roadmap, not started.</dd>
            <dt>{s_ph}</dt><dd>The control is on screen but opens <span class="ui">Under construction</span> instead of doing something.</dd>
            <dt>{s_pr}</dt><dd>On the website, shown with preview data until the E1 cloud answers it.</dd>
            <dt>{s_pk}</dt><dd>Stopped by decision; not offered and may never be built.</dd>
          </dl>
        </section>
""".format(intro=esc(meta["intro"]), total=len(features), upd=esc(meta["updated"]), shots=esc(meta["screenshotsTaken"]),
           counts="".join("<span>%d %s</span>" % (n, STATUS[s].lower()) for s, n in counts.items() if n),
           cards="\n".join(cards), news=news, dev=devlist,
           s_av=status_badge("available"), s_ud=status_badge("under-development"), s_pl=status_badge("planned"),
           s_ph=status_badge("placeholder"), s_pr=status_badge("preview"), s_pk=status_badge("parked"))
    write("guide.html", page("Overview", meta["intro"], hub, nav_toc(cats, "guide.html", [("whats-new", "What's new"), ("under-development", "Under development"), ("statuses", "What the statuses mean")]), crumbs()))

    # Catalog
    rows = []
    for i, c in enumerate(cats):
        for f in by_cat[c["id"]]:
            rows.append(
                '            <tr data-status="{st}" data-cat="{cid}"><td class="g-id">{id}</td><td>{link}<br><span class="muted">{sum}</span></td><td>{cat}</td><td>{badge}</td><td class="g-date">{since}</td><td class="g-date">{upd}</td><td>{rm}</td><td>{chk}</td><td>{topic}</td></tr>'.format(
                    st=f["status"], cid=c["id"], id=esc(f["id"]), link=feature_link(f), sum=esc(f.get("summary", "")), cat=esc(c["title"]),
                    badge=status_badge(f["status"]), since=esc(f.get("since", "")), upd=esc(f.get("updated", "")),
                    rm=esc(", ".join(f.get("roadmap", []))), chk=esc(", ".join(f.get("checks", []))), topic=esc((f.get("training") or {}).get("topic", ""))))
    opts = "".join('<option value="%s">%s</option>' % (c["id"], esc(c["title"])) for c in cats)
    sopts = "".join('<option value="%s">%s</option>' % (s, v) for s, v in STATUS.items())
    catalog = """        <h1>All features</h1>
        <p class="lead">Every feature of E1 from a user's point of view, with its category, status, the date it was delivered and the date it last changed, the roadmap stage that builds it, the review checks that test it, and the training topic it belongs to.</p>
        <div class="g-filter" role="search">
          <input type="search" placeholder="Search features" aria-label="Search features" data-guide-search>
          <select aria-label="Category" data-guide-cat><option value="">All categories</option>{opts}</select>
          <select aria-label="Status" data-guide-status><option value="">All statuses</option>{sopts}</select>
        </div>
        <p class="muted" data-guide-count>{n} features</p>
        <div class="g-table-wrap">
          <table class="g-catalog" data-guide-catalog>
            <thead><tr><th>Id</th><th>Feature</th><th>Category</th><th>Status</th><th>Since</th><th>Updated</th><th>Roadmap</th><th>Checks</th><th>Training topic</th></tr></thead>
            <tbody>
{rows}
            </tbody>
          </table>
        </div>
        <p class="g-related">The same list as data: <a href="assets/data/user-guide-features.json">user-guide-features.json</a>.</p>
""".format(opts=opts, sopts=sopts, n=len(features), rows="\n".join(rows))
    write("guide-features.html", page("All features", "Every E1 feature with status and dates.", catalog, nav_toc(cats, "guide-features.html"), crumbs("All features")))

    # Roadmap
    if roadmap:
        parts = ['        <h1>Under development and roadmap</h1>',
                 '        <p class="lead">What is built, what is being built, and what comes next, stage by stage. Taken from the build roadmap of the app (updated %s) and of the website (updated %s).</p>' % (esc(roadmap["app"]["updated"]), esc(roadmap["website"]["updated"]))]
        sections = []
        for key, label in (("app", "E1 app"), ("website", "Website")):
            for m in roadmap[key]["milestones"]:
                sid = ("%s-%s" % (key, m["id"])).lower()
                sections.append((sid, "%s · %s %s" % (label, m["id"], m["title"])))
                done = sum(1 for s in m["stages"] if s["done"])
                parts.append('        <section class="g-feature" id="%s">\n          <h2>%s %s — %s</h2>' % (sid, esc(m["id"]), esc(m["title"]), esc(label)))
                parts.append('          <div class="g-meta"><span>%d of %d stages done</span>%s</div>' % (done, len(m["stages"]), "<span>MVP</span>" if m.get("mvp") else ""))
                parts.append("          <p class=\"g-summary\">%s</p>" % esc(m["summary"]))
                parts.append('          <div class="g-table-wrap"><table class="g-steps"><thead><tr><th>Stage</th><th>What</th><th>Status</th><th>What you can try</th></tr></thead><tbody>')
                for s in m["stages"]:
                    st = "available" if s["done"] else ("parked" if m["id"] == "parked" else "planned")
                    lab = ("Done %s" % s["doneOn"]) if s["done"] and s.get("doneOn") else ("Done" if s["done"] else None)
                    badge = '<span class="g-status %s">%s</span>' % (st, esc(lab or STATUS[st]))
                    parts.append("            <tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>" % (esc(s["id"]), esc(s["title"]), badge, esc(s["tryIt"])))
                parts.append("          </tbody></table></div>\n        </section>")
        write("guide-roadmap.html", page("Under development and roadmap", "The E1 build roadmap.", "\n".join(parts) + "\n", nav_toc(cats, "guide-roadmap.html", sections), crumbs("Roadmap")))

    # The account page's User guides cards
    acc = read(os.path.join(ROOT, "account.html"))
    cards_acc = "\n".join(
        '              <a class="card guide-card" href="guide-%s.html">\n                %s\n                <h3>%s</h3>\n                <p>%s</p>\n              </a>'
        % (c["id"], c.get("icon", ""), esc(c["title"]), esc(c.get("short", c["summary"]))) for c in cats)
    acc = re.sub(r"<!-- guide:cards -->.*?<!-- /guide:cards -->", lambda m: "<!-- guide:cards -->\n" + cards_acc + "\n<!-- /guide:cards -->", acc, flags=re.S)
    write("account.html", acc)

    # Data
    data = {"updated": meta["updated"], "screenshotsTaken": meta["screenshotsTaken"], "statuses": STATUS,
            "categories": [{k: c[k] for k in ("id", "title", "summary", "training") if k in c} | {"page": "guide-%s.html" % c["id"], "order": i + 1} for i, c in enumerate(cats)],
            "features": features}
    write("assets/data/user-guide-features.json", json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    return cats, features


def check(features):
    problems = []
    ids = {}
    pages = {}
    for name in os.listdir(ROOT):
        if name.startswith("guide") and name.endswith(".html"):
            pages[name] = read(os.path.join(ROOT, name))
    anchors = {name: set(re.findall(r'id="([^"]+)"', text)) for name, text in pages.items()}
    for f in features:
        if f["id"] in ids:
            problems.append("duplicate feature id %s" % f["id"])
        ids[f["id"]] = f
        if f["status"] not in STATUS:
            problems.append("%s: unknown status %s" % (f["id"], f["status"]))
        target, _, anchor = f["page"].partition("#")
        if target not in pages or (anchor and anchor not in anchors[target]):
            problems.append("%s: page %s not found" % (f["id"], f["page"]))
    for f in features:
        for r in f.get("related", []):
            if r not in ids:
                problems.append("%s: related feature %s does not exist" % (f["id"], r))
    for name, text in pages.items():
        for href in re.findall(r'href="([^"]+)"', text):
            if href.startswith(("http", "mailto:", "assets/css", "assets/img/favicon")):
                continue
            target, _, anchor = href.partition("#")
            target = target or name
            if target.startswith("guide"):
                if target not in pages:
                    problems.append("%s: link to missing page %s" % (name, href))
                elif anchor and anchor not in anchors[target]:
                    problems.append("%s: link to missing anchor %s" % (name, href))
            elif not os.path.exists(os.path.join(ROOT, target)):
                problems.append("%s: link to missing file %s" % (name, href))
        for src in re.findall(r'<img[^>]+src="([^"]+)"', text):
            if not os.path.exists(os.path.join(ROOT, src)):
                problems.append("%s: missing image %s" % (name, src))
        for img in re.findall(r"<img[^>]*>", text):
            if 'alt="' not in img:
                problems.append("%s: image without alt: %s" % (name, img[:80]))
    return problems


if __name__ == "__main__":
    cats, features = build()
    print("Built %d categories, %d features." % (len(cats), len(features)))
    if "--check" in sys.argv:
        problems = check(features)
        for p in problems:
            print("PROBLEM:", p)
        sys.exit(1 if problems else 0)
